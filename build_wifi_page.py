"""Generate the gzip page served by the UNO: python3 build_wifi_page.py [--check]."""
from pathlib import Path
import gzip
import sys

root = Path(__file__).resolve().parent
source = (root / 'Robot/WirelessPage.h').read_text()
html = source.split('R"HTML(', 1)[1].rsplit(')HTML"', 1)[0].encode()
data = gzip.compress(html, compresslevel=9, mtime=0)
lines = [','.join(f'0x{x:02x}' for x in data[n:n+20]) for n in range(0, len(data), 20)]
generated = ('#pragma once\n// Generated by build_wifi_page.py; edit WirelessPage.h.\n'
             'static const unsigned char wirelessPageGzip[]={\n' + ',\n'.join(lines) + '\n};\n')
target = root / 'Robot/WirelessPageGzip.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != generated:
        sys.exit('Wi-Fi page changed: run python3 build_wifi_page.py before compiling.')
else:
    target.write_text(generated)
assert gzip.decompress(data) == html
print(f'Wi-Fi page: {len(html)} bytes → {len(data)} bytes gzip')
